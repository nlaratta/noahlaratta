/**
 * Every project shown on the site. Each one gets a card on /projects and its
 * own page at /projects/<slug>. `body` is Markdown, rendered at build time.
 * Keep claims in step with each repo's README.
 */

export type Category = 'Apps' | 'AI' | 'Infrastructure' | 'Data' | 'Games'

export const CATEGORIES: Category[] = ['Apps', 'AI', 'Infrastructure', 'Data', 'Games']

export type Cover =
  /** Phone screenshots on a brand-colored panel. */
  | { kind: 'phones'; background: string; images: { src: string; alt: string }[] }
  /** One wide image. */
  | { kind: 'image'; src: string; alt: string; position?: string; background?: string }
  /** No screenshot: a contour panel in the site's own palette. */
  | { kind: 'contour' }

export interface ProjectLink {
  label: string
  href: string
}

export interface Project {
  slug: string
  title: string
  /** One sentence, shown on cards. */
  summary: string
  /** When it was built, e.g. "2026" or "2025–present". */
  years: string
  /** Who built it: "Laratta Labs", "Personal project", "Team of two"… */
  context: string
  status?: 'Live' | 'Open source' | 'Archived'
  categories: Category[]
  stack: string[]
  links: ProjectLink[]
  cover: Cover
  gallery?: { src: string; alt: string; caption?: string; tall?: boolean }[]
  /** Interactive piece rendered on the project page, by name. */
  widget?: 'yardpaint-compare' | 'wordle-feedback'
  /** Shown first, with a large card, on the home page. */
  featured?: boolean
  body: string
}

