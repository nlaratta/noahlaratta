import Link from 'next/link'
import type { GetStaticPaths, GetStaticProps, InferGetStaticPropsType } from 'next'
import { serialize } from 'next-mdx-remote/serialize'
import { MDXRemote, MDXRemoteSerializeResult } from 'next-mdx-remote'
import remarkGfm from 'remark-gfm'
import Layout from '../../components/Layout'
import Container from '../../components/Container'
import ProjectCover from '../../components/ProjectCover'
import BeforeAfter from '../../components/widgets/BeforeAfter'
import WordleFeedback from '../../components/widgets/WordleFeedback'
import { getAllProjects, getProject, Project } from '../../lib/projects'
import { absUrl, breadcrumbNode } from '../../lib/seo'

function Widget({ name }: { name: NonNullable<Project['widget']> }) {
  if (name === 'yardpaint-compare') {
    return (
      <BeforeAfter
        before={{ src: '/images/projects/yardpaint/yardpaint-before.jpg', alt: 'A bare, patchy backyard before landscaping' }}
        after={{ src: '/images/projects/yardpaint/yardpaint-after.jpg', alt: 'The same backyard with a lush lawn and wildflower beds, generated by YardPaint' }}
        caption="One real generation. Drag to compare: same yard, same chairs, same fence."
      />
    )
  }
  return <WordleFeedback />
}

export default function ProjectPage({ slug, body, prev, next }: InferGetStaticPropsType<typeof getStaticProps>) {
  const project = getProject(slug)!
  const external = (href: string) => href.startsWith('http')

  const jsonLd = [
    breadcrumbNode([
      { name: 'Home', path: '/' },
      { name: 'Projects', path: '/projects' },
      { name: project.title, path: `/projects/${slug}` },
    ]),
    {
      '@type': 'CreativeWork',
      name: project.title,
      description: project.summary,
      url: absUrl(`/projects/${slug}`),
      author: { '@id': `${absUrl('/')}/#person` },
      keywords: project.stack.join(', '),
    },
  ]

  return (
    <Layout
      title={`${project.title} | Noah Laratta`}
      description={project.summary}
      path={`/projects/${slug}`}
      ogImage={`/og/project-${slug}.png`}
      jsonLd={jsonLd}
    >
      <Container className="pt-12 sm:pt-16">
        <Link href="/projects" className="text-sm text-text-secondary hover:text-primary">
          <span aria-hidden>←</span> All projects
        </Link>

        <div className="mt-8 grid gap-10 lg:grid-cols-12">
          <div className="lg:col-span-7">
            <h1 className="font-serif text-5xl font-semibold leading-[1.02] tracking-tight sm:text-6xl">{project.title}</h1>
            <p className="mt-6 text-xl leading-relaxed text-text-secondary">{project.summary}</p>
            {project.links.length > 0 && (
              <div className="mt-8 flex flex-wrap gap-3">
                {project.links.map((l, i) => (
                  <a
                    key={l.href}
                    href={l.href}
                    {...(external(l.href) ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
                    className={
                      i === 0
                        ? 'rounded-md bg-primary px-5 py-2.5 font-medium text-on-primary transition-colors hover:bg-primary-dark dark:hover:bg-primary-light'
                        : 'rounded-md border border-border px-5 py-2.5 font-medium text-foreground transition-colors hover:border-primary'
                    }
                  >
                    {l.label}
                  </a>
                ))}
              </div>
            )}
          </div>

          <dl className="self-end border-t border-border text-sm lg:col-span-4 lg:col-start-9">
            {[
              ['Built', project.years],
              ['For', project.context],
              ...(project.status ? [['Status', project.status]] : []),
              ['Stack', project.stack.join(', ')],
            ].map(([k, v]) => (
              <div key={k} className="grid grid-cols-3 gap-4 border-b border-border py-3">
                <dt className="text-text-secondary">{k}</dt>
                <dd className={`col-span-2 ${k === 'Stack' ? 'font-mono text-[13px]' : ''} ${k === 'Status' && v === 'Live' ? 'font-medium text-gold' : 'text-foreground'}`}>
                  {v}
                </dd>
              </div>
            ))}
          </dl>
        </div>

        <div className="mt-12 overflow-hidden rounded-lg border border-border">
          <ProjectCover project={project} size="hero" />
        </div>
      </Container>

      <Container narrow className="py-16 sm:py-20">
        <div className="markdown-content prose-p:text-[1.0625rem] prose-li:text-[1.0625rem]">
          <MDXRemote {...(body as MDXRemoteSerializeResult)} />
        </div>
        {project.widget && (
          <div className="mt-12">
            <Widget name={project.widget} />
          </div>
        )}
      </Container>

      {project.gallery && (
        <Container className="pb-20">
          <div className={`grid gap-6 ${project.gallery.every((g) => g.tall) ? 'grid-cols-2 sm:grid-cols-3' : 'sm:grid-cols-2'}`}>
            {project.gallery.map((g) => (
              <figure key={g.src}>
                <div className="overflow-hidden rounded-lg border border-border bg-sand">
                  <img src={g.src} alt={g.alt} loading="lazy" className="w-full" />
                </div>
                {g.caption && <figcaption className="mt-3 text-sm text-text-secondary">{g.caption}</figcaption>}
              </figure>
            ))}
          </div>
        </Container>
      )}

      <nav aria-label="More projects" className="border-t border-border">
        <Container className="grid gap-px sm:grid-cols-2">
          {[prev, next].map((p, i) =>
            p ? (
              <Link
                key={p.slug}
                href={`/projects/${p.slug}`}
                className={`group py-10 ${i === 1 ? 'sm:text-right' : ''}`}
              >
                <span className="text-sm text-text-secondary">{i === 0 ? 'Previous' : 'Next'}</span>
                <span className="mt-1 block font-serif text-2xl font-semibold tracking-tight group-hover:text-primary">{p.title}</span>
              </Link>
            ) : (
              <span key={i} />
            ),
          )}
        </Container>
      </nav>
    </Layout>
  )
}

export const getStaticPaths: GetStaticPaths = async () => ({
  paths: getAllProjects().map((p) => ({ params: { slug: p.slug } })),
  fallback: false,
})

export const getStaticProps: GetStaticProps<{
  slug: string
  body: MDXRemoteSerializeResult
  prev: { slug: string; title: string } | null
  next: { slug: string; title: string } | null
}> = async ({ params }) => {
  const slug = params!.slug as string
  const all = getAllProjects()
  const i = all.findIndex((p) => p.slug === slug)
  const pick = (p?: Project) => (p ? { slug: p.slug, title: p.title } : null)
  const body = await serialize(all[i].body.trim(), { mdxOptions: { remarkPlugins: [remarkGfm] } })
  return { props: { slug, body, prev: pick(all[i - 1]), next: pick(all[i + 1]) } }
}
